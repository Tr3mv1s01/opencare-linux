def explain_error(error):
    text = str(error)
    lower = text.lower()
    if 'dconf' in lower or 'сеанс' in lower:
        return 'Не удалось изменить настройки рабочего стола. Запускайте OpenCare из обычного меню или терминала вашего пользователя, без sudo. Исходное значение могло остаться без изменений.'
    if 'permission' in lower or 'отказано' in lower:
        return 'Linux не разрешил доступ к этому файлу или папке. Выберите папку, принадлежащую вашему пользователю. Не нужно запускать всю программу от администратора.'
    if 'измен' in lower and ('файл' in lower or 'настройк' in lower):
        return 'Этот файл или параметр уже изменился после предыдущего действия. OpenCare не будет перезаписывать новую версию. Обновите список и проверьте текущее состояние.'
    if 'utf-8' in lower or 'бинарн' in lower:
        return 'Этот файл нельзя открыть как обычный текст. Изменяйте его через настройки программы, которой он принадлежит.'
    return 'Действие не удалось завершить. Прочитайте пояснение ниже. Если оно непонятно, сохраните подробности и передайте их вместе с описанием того, что вы нажали.'
